function ficha({ perfil, etapa, requisito, documentacion, extra }) {
  const docs = documentacion
    ? `Documentación para la inscripción: ${documentacion}`
    : null
  return [perfil, `Lugar: ${SEDE}.`, `Etapa de formación profesional: ${etapa}.`, `Requisito de ingreso: ${requisito}.`, docs, extra, GRATIS]
    .filter(Boolean)
    .join(' ')
}

